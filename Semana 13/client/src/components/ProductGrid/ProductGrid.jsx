import ProductCard from "../ProductCard/index.js";

export default function ProductGrid({ products, onEdit, onDelete }) {
  return (
    <div className="product-grid">
      {products.map((product) => (
        <ProductCard
          key={product.id}
          product={product}
          onEdit={onEdit}
          onDelete={onDelete}
        />
      ))}
    </div>
  );
}
